-- Remove old tables only if you are restarting the migration.
DROP TABLE IF EXISTS alerts CASCADE;
DROP TABLE IF EXISTS control_actions CASCADE;
DROP TABLE IF EXISTS schedules CASCADE;
DROP TABLE IF EXISTS sensor_logs CASCADE;
DROP TABLE IF EXISTS wards CASCADE;
DROP TABLE IF EXISTS devices CASCADE;
DROP TABLE IF EXISTS users CASCADE;

-- ------------------------------------------------------------
-- Users
-- ------------------------------------------------------------
CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,

    role VARCHAR(20) NOT NULL DEFAULT 'user'
        CHECK (role IN ('user', 'operator')),

    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at TIMESTAMPTZ
);

-- ------------------------------------------------------------
-- Devices
-- ------------------------------------------------------------
CREATE TABLE devices (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_key VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL DEFAULT 'ESP32 Main Controller',
    ip_address VARCHAR(45) NOT NULL,
    tank_capacity_ml INTEGER NOT NULL DEFAULT 5000,
    is_online BOOLEAN NOT NULL DEFAULT FALSE,
    last_seen_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ------------------------------------------------------------
-- Wards
-- ------------------------------------------------------------
CREATE TABLE wards (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id INTEGER NOT NULL
        REFERENCES devices(id) ON DELETE CASCADE,

    ward_number SMALLINT NOT NULL
        CHECK (ward_number BETWEEN 1 AND 3),

    ward_name VARCHAR(100) NOT NULL,
    valve_gpio VARCHAR(10),

    UNIQUE (device_id, ward_number)
);

-- ------------------------------------------------------------
-- Sensor history
-- ------------------------------------------------------------
CREATE TABLE sensor_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    device_id INTEGER NOT NULL
        REFERENCES devices(id) ON DELETE CASCADE,

    tank_level_ml INTEGER NOT NULL,
    flow_rate_lpm NUMERIC(6,2) NOT NULL DEFAULT 0,

    ward1_ml INTEGER NOT NULL DEFAULT 0,
    ward2_ml INTEGER NOT NULL DEFAULT 0,
    ward3_ml INTEGER NOT NULL DEFAULT 0,

    active_ward SMALLINT NOT NULL DEFAULT 0
        CHECK (active_ward BETWEEN 0 AND 3),

    street_light BOOLEAN NOT NULL DEFAULT FALSE,

    light_mode VARCHAR(20) NOT NULL DEFAULT 'auto'
        CHECK (
            light_mode IN (
                'auto',
                'manual_on',
                'manual_off'
            )
        ),

    leak_detected BOOLEAN NOT NULL DEFAULT FALSE,
    dry_tank BOOLEAN NOT NULL DEFAULT FALSE,

    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_sensor_logs_device_time
ON sensor_logs(device_id, recorded_at);

-- ------------------------------------------------------------
-- Water distribution schedules
-- ------------------------------------------------------------
CREATE TABLE schedules (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    device_id INTEGER NOT NULL
        REFERENCES devices(id) ON DELETE CASCADE,

    ward_number SMALLINT NOT NULL
        CHECK (ward_number BETWEEN 1 AND 3),

    start_time TIME NOT NULL,
    end_time TIME NOT NULL,

    days_mask VARCHAR(27) NOT NULL
        DEFAULT 'MON,TUE,WED,THU,FRI,SAT,SUN',

    quota_ml INTEGER NOT NULL DEFAULT 1500,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_by INTEGER NOT NULL
        REFERENCES users(id),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ------------------------------------------------------------
-- Operator control history
-- ------------------------------------------------------------
CREATE TABLE control_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    device_id INTEGER NOT NULL
        REFERENCES devices(id) ON DELETE CASCADE,

    user_id INTEGER NOT NULL
        REFERENCES users(id),

    action_type VARCHAR(30) NOT NULL
        CHECK (
            action_type IN (
                'valve_open',
                'valve_close',
                'light_on',
                'light_off',
                'light_auto',
                'refill'
            )
        ),

    target_ward SMALLINT
        CHECK (
            target_ward IS NULL
            OR target_ward BETWEEN 1 AND 3
        ),

    result VARCHAR(20) NOT NULL DEFAULT 'success'
        CHECK (result IN ('success', 'failed')),

    notes VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ------------------------------------------------------------
-- Alerts
-- ------------------------------------------------------------
CREATE TABLE alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    device_id INTEGER NOT NULL
        REFERENCES devices(id) ON DELETE CASCADE,

    alert_type VARCHAR(30) NOT NULL
        CHECK (
            alert_type IN (
                'leak',
                'dry_tank',
                'device_offline',
                'low_level'
            )
        ),

    severity VARCHAR(20) NOT NULL DEFAULT 'warning'
        CHECK (
            severity IN (
                'info',
                'warning',
                'critical'
            )
        ),

    message VARCHAR(255) NOT NULL,
    is_resolved BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ
);

CREATE INDEX idx_alerts_device_resolved
ON alerts(device_id, is_resolved);

