CREATE TABLE IF NOT EXISTS activity_logs (
  id BIGSERIAL PRIMARY KEY,
  device_id BIGINT NULL,
  user_id BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
  actor_name VARCHAR(150),
  actor_role VARCHAR(30),
  action_type VARCHAR(100) NOT NULL,
  category VARCHAR(40) NOT NULL DEFAULT 'system',
  description TEXT NOT NULL,
  severity VARCHAR(20) NOT NULL DEFAULT 'info',
  result VARCHAR(20) NOT NULL DEFAULT 'success',
  target_type VARCHAR(60),
  target_id VARCHAR(100),
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  ip_address VARCHAR(100),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

  CONSTRAINT activity_logs_category_check
    CHECK (
      category IN (
        'authentication',
        'water',
        'lighting',
        'schedule',
        'user',
        'device',
        'report',
        'system'
      )
    ),

  CONSTRAINT activity_logs_severity_check
    CHECK (
      severity IN (
        'info',
        'success',
        'warning',
        'critical'
      )
    ),

  CONSTRAINT activity_logs_result_check
    CHECK (
      result IN (
        'success',
        'failed'
      )
    )
);

CREATE INDEX IF NOT EXISTS idx_activity_logs_created_at
  ON activity_logs(created_at DESC);

CREATE INDEX IF NOT EXISTS idx_activity_logs_user_id
  ON activity_logs(user_id);

CREATE INDEX IF NOT EXISTS idx_activity_logs_category
  ON activity_logs(category);

CREATE INDEX IF NOT EXISTS idx_activity_logs_severity
  ON activity_logs(severity);


